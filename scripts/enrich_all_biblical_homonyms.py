def apply_homonyms():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()

    for h in homonym_entries:
        cur.execute("SELECT id FROM bible_dictionary WHERE name_ko = ?", (h["name_ko"],))
        row = cur.fetchone()
        if row:
            cur.execute("""
                UPDATE bible_dictionary
                SET name_en = ?, name_original = ?, category = ?, meaning = ?, summary = ?, events = ?, key_verses = ?, aliases = ?
                WHERE id = ?
            """, (
                h["name_en"], h["name_original"], h["category"], h["meaning"], h["summary"],
                h["events"], h["key_verses"], h["aliases"], row[0]
            ))
            print(f"✅ 동명이인 해설 전면 보강: {h['name_ko']} (ID: {row[0]})")
        else:
            cur.execute("""
                INSERT INTO bible_dictionary (name_ko, name_en, name_original, category, meaning, summary, events, key_verses, aliases)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, (
                h["name_ko"], h["name_en"], h["name_original"], h["category"], h["meaning"],
                h["summary"], h["events"], h["key_verses"], h["aliases"]
            ))
            print(f"✨ 신규 동명이인 독립 항목 생성: {h['name_ko']}")

    conn.commit()
    conn.close()

    print("\n📦 bible.db.gz 최종 압축 갱신 중...")
    with open(DB_PATH, 'rb') as f_in:
        with gzip.open(DB_GZ_PATH, 'wb', compresslevel=9) as f_out:
            shutil.copyfileobj(f_in, f_out)
            
    print("🎉 성경 대표 동명이인 정밀 보강 완료!")

if __name__ == '__main__':
    apply_homonyms()
