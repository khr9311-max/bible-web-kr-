for term in biblical_terms_and_units:
    cur.execute("""
        INSERT INTO bible_dictionary (name_ko, name_en, name_original, category, meaning, summary, events, key_verses, aliases)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT(id) DO UPDATE SET
            name_en = excluded.name_en,
            name_original = excluded.name_original,
            category = excluded.category,
            meaning = excluded.meaning,
            summary = excluded.summary,
            events = excluded.events,
            key_verses = excluded.key_verses,
            aliases = excluded.aliases;
    """, (
        term["name_ko"], term["name_en"], term["name_original"], term["category"],
        term["meaning"], term["summary"], term["events"], term["key_verses"], term["aliases"]
    ))
    inserted_terms += 1

conn.commit()
print(f"Successfully added {inserted_terms} comprehensive Biblical Terms & Units (단어·도량형)!")

